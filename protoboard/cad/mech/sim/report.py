"""Table of every simulation run (out/mech/sim/tier-<t>/<scenario>.json) for the decision record and the report.

    python3 cad/mech/sim/report.py   ->  docs/sim-results.json and .md

Right arm (it carries the 0.25 kg payload): per gravity joint the peak servo torque as a fraction of stall, the mean
as a fraction of the rated third of stall, the worst tracking error, the peak belt tension (rated 179.6 N) and the
share of time the servo sat at its torque limit. Base: tilt and the push force that tipped it.
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from summarise import summary  # noqa: E402

PROJECT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
SIM = os.path.join(PROJECT, "out", "mech", "sim")
JOINTS = ["r_j1", "r_j2", "r_j4"]
BELT_RATED = 179.6

rows = []
for d in sorted(os.listdir(SIM)):
    if not d.startswith("tier-"):
        continue
    tier = d[5:]
    for f in sorted(os.listdir(os.path.join(SIM, d))):
        if not f.endswith(".json") or f == "links.json":
            continue
        s = summary(tier, f[:-5])
        r = {"tier": tier, "scenario": f[:-5], "tip_force_N": s["tip_force_N"], "tilt_max_deg": s["base"].get("tilt_max_deg")}
        for j in JOINTS:
            w = s["joints"].get(j)
            if w:
                w = w[0]
                r[j] = {k: w[k] for k in ("stall_frac_max", "rated_frac_mean", "err_deg", "belt_N_max", "sat_frac")}
        rows.append(r)
json.dump(rows, open(os.path.join(PROJECT, "docs", "sim-results.json"), "w"), indent=1)
L = ["# Simulation results (generated by cad/mech/sim/report.py; do not edit)", "", __doc__.split("\n\n", 1)[1].strip(), "",
     "| Tier | Scenario | " + " | ".join(f"{j} stall peak / rated mean / err deg / belt N / sat" for j in JOINTS) + " | Tilt deg | Tip N |",
     "|---|---|" + "---|" * (len(JOINTS) + 2)]
for r in rows:
    cells = []
    for j in JOINTS:
        w = r.get(j)
        cells.append("-" if not w else f"{w['stall_frac_max']:.2f} / {w['rated_frac_mean']:.2f} / {w['err_deg']:.1f} / {w['belt_N_max']:.0f}"
                     f"{' (over)' if w['belt_N_max'] > BELT_RATED else ''} / {w['sat_frac']:.2f}")
    tip = f"{r['tip_force_N']:.0f}" if r["tip_force_N"] else "-"
    L.append(f"| {r['tier'].upper()} | {r['scenario']} | " + " | ".join(cells) + f" | {r['tilt_max_deg'] or 0:.1f} | {tip} |")
open(os.path.join(PROJECT, "docs", "sim-results.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L[4:]))
