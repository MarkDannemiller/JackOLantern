"""Generate the UHD sources of the mechanical model from src/mech/mech.json and src/mech/tier-<t>.json.

    python3 cad/mech/gen_uhd.py

Writes (generated; never edit by hand):
  src/mech/parts.gen.uhd.ts        printed and cut parts (mechPart)
  parts/local/mech/bought.gen.uhd.ts   bought mechanical parts (bearings, belts, springs, extrusions, flanges...)
  parts/local/mech/hw.gen.uhd.ts   hardware (screws, nuts, inserts, washers, T-nuts) + hw/<id>/cad.config.ts
  src/mech/stacks.gen.uhd.ts       one fastener-stack harness per distinct joint
  src/mech/body.gen.uhd.ts         jj-body-a / -b / -c: base, mast, torso, neck, electronics board and trays
  src/mech/assembly.gen.ts         per tier and side: the arm's mechanical children, links and exports; the
                                   root-level children (harnesses) and links (feet, trays, head)
"""
from __future__ import annotations

import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
PROJECT = os.path.abspath(os.path.join(HERE, "..", ".."))
SRC = os.path.join(PROJECT, "src", "mech")
LOCAL = os.path.join(PROJECT, "parts", "local", "mech")
DB = json.load(open(os.path.join(SRC, "mech.json")))["parts"]
TIERS = {t: json.load(open(os.path.join(SRC, f"tier-{t}.json"))) for t in "abc"}

# mechanical part -> the existing (electrical) definition that carries it
MAPPED = {
    "servo-sts3215": "feetech-sts3215-c047", "servo-sts3250": "feetech-sts3250", "servo-ds3235": "dsservo-ds3235",
    "servo-ds3225": "dsservo-ds3225mg-270", "servo-mg996r": "towerpro-mg996r",
    "jj-body-ideal_diode": "ideal-diode-40a", "jj-body-monitor": "adafruit-ina228", "jj-body-lvc": "xh-m609-lvc", "jj-body-fuses": "fuse-block-6way",
    "jj-body-relay": "temco-relay-24v-40a", "jj-body-drok": "drok-300w-buck", "jj-body-ekylin": "ekylin-12v-20a-buck",
    "jj-body-bus": "waveshare-bus-servo-adapter-a", "jj-body-pca": "pca9685-16ch-servo-driver-0x41", "jj-body-fuse_inline": "inline-atc-fuse",
    "jj-body-dock": "m18-power-wheel-adapter", "jj-body-pack": "milwaukee-m18-pack", "jj-body-estop": "estop-22mm-nc",
    "jj-head-assembly": "jj-head", "pollen-amazinghand-r": "pollen-amazinghand-kit", "pollen-amazinghand-l": "pollen-amazinghand-kit-l",
    "jj-body-pololu": "pololu-d24v50f5 / pololu-d36v50f5",
}
# bodies whose definition is a catalog part (no local definition to carry them): their mates are left out
UNCARRIED = {"jj-body-pi5"}
# pololu D24 and D36 share a body; Pi 5 is a catalog part (not given a body here)
SHARED_BODY = {"pololu-d24v50f5": "jj-body-pololu", "pololu-d36v50f5": "jj-body-pololu"}

# mech instance ids -> the arm module's existing child ids
ARM_RENAME = {
    "a": {"j1_servo": "shoulder_flex", "j2_servo": "shoulder_out", "j4_servo": "elbow", "hand/grip_servo": "grip"},
    "b": {"j1_servo": "shoulder_flex", "j2_servo": "shoulder_out", "j3_servo": "upper_twist", "j4_servo": "elbow", "j5_servo": "wrist_twist",
          "hand/fingers_servo": "fingers", "hand/thumb_servo": "thumb"},
    "c": {"j1_servo": "shoulder_flex", "j2_servo": "shoulder_out", "j3_servo": "upper_twist", "j4_servo": "elbow", "j5_servo": "wrist_twist",
          "hand/j6_servo": "wrist_pitch", "hand/amazinghand": "hand"},
}
ROOT_RENAME = {"body__arm_r__bus_adapter": ("arm_r", "bus_adapter"), "body__arm_l__bus_adapter": ("arm_l", "bus_adapter")}


def const(pid):
    return "M_" + re.sub(r"[^A-Za-z0-9]+", "_", pid).upper()


def ts_str(s):
    return json.dumps(s)


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    old = open(path).read() if os.path.exists(path) else None
    if old != text:
        open(path, "w").write(text)


HEADER = "// GENERATED by cad/mech/gen_uhd.py from src/mech/*.json (cad/mech/build.py). Do not edit.\n"


def part_kind(pid):
    e = DB[pid]
    if pid in MAPPED:
        return "mapped"
    if pid in UNCARRIED:
        return "uncarried"
    if e["category"] == "hardware":
        return "hardware"
    if e["category"] == "costume":
        return "costume"
    if e["category"] in ("printed", "cut"):
        return "designed"
    return "bought"


def main():
    used = set()
    for t in TIERS.values():
        for i in t["instances"].values():
            used.add(i["part"])
        for m in t["mates"]:
            for s in m["stack"]:
                used.add(s["part"])
    kinds = {pid: part_kind(pid) for pid in used}

    # ---------------- part definitions
    designed = sorted(p for p, k in kinds.items() if k == "designed")
    bought = sorted(p for p, k in kinds.items() if k == "bought")
    hardware = sorted(p for p, k in kinds.items() if k == "hardware")
    write(os.path.join(SRC, "parts.gen.uhd.ts"), HEADER + 'import type { ModuleDef } from "@deltarobotics/uhd";\nimport { mechPart } from "./lib";\n\n'
          + "".join(f"export const {const(p)}: ModuleDef = mechPart({ts_str(p)});\n" for p in designed))
    write(os.path.join(LOCAL, "bought.gen.uhd.ts"), HEADER + 'import type { ModuleDef } from "@deltarobotics/uhd";\nimport { mechPart } from "../../../src/mech/lib";\n\n'
          + "".join(f"export const {const(p)}: ModuleDef = mechPart({ts_str(p)});\n" for p in bought))
    write(os.path.join(LOCAL, "hw.gen.uhd.ts"), HEADER + 'import type { ModuleDef } from "@deltarobotics/uhd";\nimport { hardwarePart } from "../../../src/mech/lib";\n\n'
          + "".join(f"export const {const(p)}: ModuleDef = hardwarePart({ts_str(p)});\n" for p in hardware))
    for p in hardware:
        write(os.path.join(LOCAL, "hw", p, "cad.config.ts"),
              f'{HEADER}import {{ defineCapabilityConfig }} from "@protoboardai/core";\n\nexport default defineCapabilityConfig({{ provider: "@protoboardai/ext-frame-cad", module: {ts_str(p)} }});\n')

    # ---------------- fastener stacks: one harness per distinct (stack, hole count)
    stacks = {}

    def stack_id(m, holes):
        sig = json.dumps([m["stack"], holes], sort_keys=True)
        if sig not in stacks:
            parts = {}
            for s in m["stack"]:
                parts[s["part"]] = parts.get(s["part"], 0) + 1
            screw = next((s for s in m["stack"] if DB[s["part"]]["hardware"].get("kind") == "screw"), None)
            base = DB[screw["part"]]["name"].split(",")[0] if screw else DB[m["stack"][0]["part"]]["name"]
            hid = f"jj-joint-{len(stacks) + 1:03d}"
            stacks[sig] = (hid, f"{holes} x {base}", m["stack"], holes)
        return stacks[sig][0]

    def holes_of(tier, m):
        a_iid, a_fid = m["a"]
        f = DB[TIERS[tier]["instances"][a_iid]["part"]]["features"][a_fid]
        p = f["params"]
        if p.get("shape") in (None, "positions"):
            return len(p.get("positions", [[0, 0]]))
        return int(p.get("count") or 1)

    # ---------------- per tier: modules
    body_defs, asm = [], {}
    for t, T in TIERS.items():
        inst = T["instances"]
        mod = {iid: i["module"] for iid, i in inst.items()}

        def uid(iid):
            """(module, child id) of an instance."""
            m = mod[iid]
            if m in ("arm_r", "arm_l"):
                local = iid.split("/", 1)[1]
                return m, ARM_RENAME[t].get(local, local.replace("/", "__"))
            if m == "root":
                if iid in ROOT_RENAME:
                    return ROOT_RENAME[iid]
                return "root", iid[len("body__"):] if iid.startswith("body__") else iid
            return m, iid.replace("/", "__")

        def defid(iid):
            p = inst[iid]["part"]
            k = kinds[p]
            return MAPPED.get(p, p) if k == "mapped" else p

        body_children, body_links, body_exports = [], [], {}
        arm = {s: dict(children=[], links=[], exports={}) for s in ("r", "l")}
        root_children, root_links = [], []
        for iid, i in inst.items():
            if mod[iid] == "costume":
                continue
            m, cid = uid(iid)
            p = i["part"]
            if kinds[p] == "mapped" and m in ("arm_r", "arm_l") and cid in set(ARM_RENAME[t].values()):
                continue                        # the arm module already has this child (its electrical definition)
            if m == "root":
                continue                        # root children exist already (electronics, head)
            if m == "body":
                body_children.append(dict(id=cid, moduleDefId=defid(iid), name=DB[p]["name"]))
            else:
                arm[m[-1]]["children"].append(dict(id=cid, moduleDefId=defid(iid), name=DB[p]["name"]))

        def export(scope, child, fid):
            """Export a child's interface from a module; returns the export id."""
            eid = f"{child}__{fid}"
            if scope == "body":
                body_exports[eid] = dict(id=eid, name=f"{child} {fid}", **{"from": dict(child=child, interfaceId=fid)})
            else:
                arm[scope[-1]]["exports"][eid] = dict(id=eid, name=f"{child} {fid}", **{"from": dict(child=child, interfaceId=fid)})
            return eid

        def fid_of(iid, fid):
            return fid

        for m in T["mates"]:
            (ia, fa), (ib, fb) = m["a"], m["b"]
            if mod[ia] == "costume" or mod[ib] == "costume":
                continue
            if inst[ia]["part"] in UNCARRIED or inst[ib]["part"] in UNCARRIED:
                continue
            ma, ca = uid(ia)
            mb, cb = uid(ib)
            fa, fb = fid_of(ia, fa), fid_of(ib, fb)
            link = dict(id=re.sub(r"[^A-Za-z0-9_]+", "_", m["id"]), name=m["id"].replace("_", " "))
            if m["gap"] or m["rot"]:
                link["mate"] = {**({"gapMm": round(m["gap"], 4)} if m["gap"] else {}), **({"rotationDeg": round(m["rot"], 4)} if m["rot"] else {})}
            harness = None
            if m["stack"]:
                harness = stack_id(m, holes_of(t, m))
            if ma == mb and ma != "root":
                scope = ma
                link["a"] = dict(child=ca, interfaceId=fa)
                link["b"] = dict(child=cb, interfaceId=fb)
            else:
                scope = "root"
                link["a"] = dict(child=ca, interfaceId=fa) if ma == "root" else dict(child=ma if ma != "body" else "body", interfaceId=export(ma, ca, fa))
                link["b"] = dict(child=cb, interfaceId=fb) if mb == "root" else dict(child=mb if mb != "body" else "body", interfaceId=export(mb, cb, fb))
            if harness:
                hc = f"j_{link['id']}"
                link["harness"] = hc
                ch = dict(id=hc, moduleDefId=harness, name=f"Hardware: {m['id'].replace('_', ' ')}")
                {"body": body_children, "root": root_children}.get(scope, arm.get(scope[-1], {}).get("children") if scope.startswith("arm") else None).append(ch)
            {"body": body_links, "root": root_links}.get(scope, arm[scope[-1]]["links"] if scope.startswith("arm") else None).append(link)
        body_defs.append(dict(id=f"jj-body-{t}", name=f"Body, tier {t.upper()}: base, mast, torso, neck and electronics board",
                              children=body_children, links=body_links, exports=list(body_exports.values())))
        asm[t] = dict(arm={s: dict(children=a["children"], links=a["links"], exports=list(a["exports"].values())) for s, a in arm.items()},
                      root=dict(children=root_children, links=root_links))

    # ---------------- write the harnesses, bodies and assembly data
    lines = [HEADER, 'import type { ModuleDef } from "@deltarobotics/uhd";\nimport { stackHarness } from "./lib";\n\n']
    for sig, (hid, name, stack, holes) in sorted(stacks.items(), key=lambda kv: kv[1][0]):
        lines.append(f"export const {const(hid)}: ModuleDef = stackHarness({ts_str(hid)}, {ts_str(name)}, {json.dumps(stack)}, {holes});\n")
    write(os.path.join(SRC, "stacks.gen.uhd.ts"), "".join(lines))
    out = [HEADER, 'import type { ModuleDef } from "@deltarobotics/uhd";\n\n']
    for b in body_defs:
        out.append(f"export const {const(b['id'])}: ModuleDef = {{\n  id: {ts_str(b['id'])},\n  name: {ts_str(b['name'])},\n  kind: \"module\",\n"
                   f"  categories: [\"mechanical.structure\"],\n  tags: [\"body\"],\n  interfaces: [],\n"
                   f"  children: {json.dumps(b['children'], indent=1)},\n  links: {json.dumps(b['links'], indent=1)},\n  exports: {json.dumps(b['exports'], indent=1)},\n}} as unknown as ModuleDef;\n\n")
    write(os.path.join(SRC, "body.gen.uhd.ts"), "".join(out))
    write(os.path.join(SRC, "assembly.gen.ts"), HEADER + "export const MECH = " + json.dumps(asm, indent=1) + " as const;\n")
    print(f"{len(designed)} designed, {len(bought)} bought, {len(hardware)} hardware parts; {len(stacks)} fastener stacks")
    for t in "abc":
        print(t, "body", len(body_defs["abc".index(t)]["children"]), "children", len(body_defs["abc".index(t)]["links"]), "links;",
              "arm", len(asm[t]["arm"]["r"]["children"]), "children", len(asm[t]["arm"]["r"]["links"]), "links;",
              "root", len(asm[t]["root"]["children"]), "children", len(asm[t]["root"]["links"]), "links")


if __name__ == "__main__":
    main()


# ------------------------------------------------------------------------------ build-guide steps
MAX_MATES = 8
STEP_TITLES = {
    "base": "Build the base: skirt, bucket, flanges and mast",
    "torso": {"a": "Build the plywood torso on the top flange", "b": "Build the torso frame on the top flange", "c": "Build the torso frame on the top flange"},
    "neck": "Fit the neck posts and the neck plate",
    "electronics": "Fit the electronics board, its trays and the E-stop bracket",
    "electronics_root": "Put the power parts in their trays and bolt down the battery docks",
    "shoulder": "{side} arm: shoulder housing, J1 servo, belt and springs",
    "balancer": "{side} arm: shoulder balancer (lever, sheaves, springs and cord)",
    "upper": "{side} arm: yoke and upper arm (shoulder-out and twist joints)",
    "elbow": "{side} arm: elbow housing and elbow drive",
    "forearm": "{side} arm: forearm and wrist-twist joint",
    "hand": "{side} arm: hand",
    "wrist": "{side} arm: wrist pitch and hand",
    "arms": "Mount the arms on the torso",
    "head": "Fit the head on the neck plate",
    "battery": "Slide the battery packs onto the docks",
}
STEP_NOTES = {
    "base": [("caution", "Concrete is heavy and sets fast: pour it in the bucket where it will stand, set the bottom flange on the first pour with the mast plumb, pour the rest round it and let it cure before loading the mast.")],
    "torso": [("tip", "Roll each T-nut into its slot before closing the rail; fit brackets loosely, square the box, then tighten.")],
    "shoulder": [("tip", "Press every heat-set insert into the printed parts first (soldering iron with an insert tip)."),
                 ("tip", "Loop the belt on both pulleys before the cap goes on; the centre distance is fixed, so check it skips no tooth when you turn the joint by hand under load.")],
    "balancer": [("caution", "The springs are under load whenever the cord is tied: tie it with the arm hanging, and keep fingers clear of the sheaves when the arm swings."),
                 ("tip", "Cut the cord so each spring is stretched by the amount in the equaliser's note with the arm hanging; the shoulder servo then needs little torque to hold the arm at any forward angle.")],
    "head": [("warning", "The head's base screw pattern is not in the received CAD: mark and drill the neck plate from the head itself before this step.")],
    "battery": [("caution", "Fit the packs last, with the E-stop pressed in, after the wiring has been checked.")],
}


def write_steps():
    steps = {}
    for t, T in TIERS.items():
        inst = T["instances"]
        mod = {iid: i["module"] for iid, i in inst.items()}
        groups = {}
        for m in T["mates"]:
            (ia, _), (ib, _) = m["a"], m["b"]
            if "costume" in (mod[ia], mod[ib]) or inst[ia]["part"] in UNCARRIED or inst[ib]["part"] in UNCARRIED:
                continue
            ma, mb = mod[ia], mod[ib]
            lid = re.sub(r"[^A-Za-z0-9_]+", "_", m["id"])
            if ma == mb and ma != "root":
                scope = ma
                path = f"{ma}/{lid}"
                key = (scope, m["step"])
            else:
                path = lid
                st = m["step"]
                key = ("root", "electronics_root" if st == "electronics" else st)
            groups.setdefault(key, []).append(path)
        order = [("body", "base"), ("body", "torso"), ("body", "neck"), ("body", "electronics"), ("root", "electronics_root")]
        for side in ("r", "l"):
            for st in ("shoulder", "balancer", "upper", "elbow", "forearm", "hand", "wrist"):
                order.append((f"arm_{side}", st))
        order += [("root", "arms"), ("root", "head"), ("root", "battery")]
        out = []
        for key in order:
            if key not in groups:
                continue
            scope, st = key
            title = STEP_TITLES[st]
            if isinstance(title, dict):
                title = title[t]
            side = "Right" if scope == "arm_r" else "Left" if scope == "arm_l" else ""
            sid = f"{scope}-{st}".replace("_", "-")
            mates = groups[key]                      # in build order (the order the model was assembled)
            n = max(1, -(-len(mates) // MAX_MATES))
            size = -(-len(mates) // n)
            for k in range(n):
                chunk = mates[k * size:(k + 1) * size]
                out.append(dict(id=sid + (f"-{k + 1}" if n > 1 else ""), title=title.format(side=side) + (f" ({k + 1} of {n})" if n > 1 else ""),
                                mates=chunk,
                                notes=[dict(kind=kk, text=x) for kk, x in STEP_NOTES.get(st, [])] if (k == 0 and not (scope == "arm_l" and st in STEP_NOTES)) else [],
                                **({"after": "test"} if st == "battery" else {})))
        left = set(groups) - set(order)
        assert not left, left
        steps[t] = out
    os.makedirs(os.path.join(PROJECT, "docs"), exist_ok=True)
    write(os.path.join(PROJECT, "docs", "assembly-steps.gen.json"), json.dumps(steps, indent=1) + "\n")
    print("steps:", {t: len(v) for t, v in steps.items()})


write_steps()
